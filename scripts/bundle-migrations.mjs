// Bundles supabase/migrations/*.sql into ONE paste-ready file for the Supabase
// SQL editor (Project → SQL Editor → New query → paste → Run).
//
//   npm run db:bundle            # writes supabase/deploy-all.sql
//
// The output is generated, never hand-edited. The migrations are idempotent, so
// re-running the bundle against a project that already has some of them is safe.
// Verify before deploying with:  npm run db:verify
//
// To check the *bundle* itself (not the individual files) through the same
// embedded-postgres gate:
//   npm run db:bundle
//   mkdir -p .local-pg/bundle && cp supabase/deploy-all.sql .local-pg/bundle/
//   STUDYLAB_MIGRATIONS_DIR=.local-pg/bundle npm run db:verify

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MIGRATIONS_DIR = join(ROOT, "supabase", "migrations");
const OUT = join(ROOT, "supabase", "deploy-all.sql");

/** The same ordering the verification harness uses: sorted by filename. */
export function migrationFiles(dir = MIGRATIONS_DIR) {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".sql"))
    .sort();
}

/**
 * `create policy` has no "if not exists", so a second run aborts with
 * "policy ... already exists" — the bundle would not survive a partial paste.
 * Emit a matching `drop policy if exists` in front of each one (the same trick
 * migration 0008 already uses by hand). The policy is recreated identically on
 * the next line, so this changes nothing on a first run.
 */
export function makePoliciesRerunnable(sql) {
  return sql.replace(
    /create policy\s+("[^"]+"|[A-Za-z0-9_]+)\s+on\s+([A-Za-z0-9_."]+)/gi,
    (create, name, table) => `drop policy if exists ${name} on ${table};\n${create}`,
  );
}

export function buildBundle(dir = MIGRATIONS_DIR) {
  const files = migrationFiles(dir);
  if (files.length === 0) throw new Error(`no .sql files found in ${dir}`);

  const header = [
    "-- StudyLab — full schema, generated file. DO NOT EDIT.",
    `-- Generated by scripts/bundle-migrations.mjs from ${files.length} migrations:`,
    ...files.map((f) => `--   ${f}`),
    "--",
    "-- Paste this whole file into the Supabase SQL editor and run it once.",
    "-- Verified with `npm run db:verify` (embedded PostgreSQL + Supabase stubs):",
    "-- applies clean, twice in a row, RLS on every public table.",
    "",
  ].join("\n");

  const body = files
    .map((file) => {
      const sql = makePoliciesRerunnable(readFileSync(join(dir, file), "utf8"));
      const banner = `\n-- ============================================================\n-- ${file}\n-- ============================================================\n`;
      // A file ending in a comment with no newline would swallow the next
      // statement, so always terminate with a newline.
      return banner + (sql.endsWith("\n") ? sql : sql + "\n");
    })
    .join("\n");

  return header + body;
}

const bundle = buildBundle();

// Only write when run directly (`npm run db:bundle`); scripts/local-db.mjs
// imports buildBundle() to check the committed copy is not stale.
const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (isMain) {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, bundle);

  const lines = bundle.split("\n").length;
  const drops = (bundle.match(/^drop policy if exists /gim) ?? []).length;
  console.log(`[bundle] ${migrationFiles().length} migrations -> supabase/deploy-all.sql`);
  console.log(`[bundle] ${lines} lines, ${(Buffer.byteLength(bundle) / 1024).toFixed(1)} kB`);
  console.log(`[bundle] ${drops} "drop policy if exists" guards added so a re-run cannot abort`);
  console.log(`[bundle] written to ${resolve(OUT)}`);
}
